import * as THREE from "three";
import { createWarpedEdge } from "./borderGeometry.js";


// ============================================================
// EDGE REGISTRY
// ============================================================
//
// Хранилище общих границ субсекторов.
//
// Главная задача:
//
// createEdge(A, B)
// createEdge(B, A)
//
// должны обращаться к ОДНОМУ И ТОМУ ЖЕ ребру.
//
// Благодаря этому соседние субсекторы будут использовать
// одну и ту же геометрию границы.
//
// ============================================================


// ============================================================
// НАСТРОЙКИ
// ============================================================

// Количество знаков после запятой при создании ключа.
//
// Нужно, потому что Vector3 работает с числами с плавающей
// точкой, и две математически одинаковые точки могут иметь
// небольшое отличие:
//
// 0.123456789
// 0.123456791
//
// Для нас это одна и та же вершина.
const PRECISION = 6;


// ============================================================
// СОЗДАНИЕ РЕЕСТРА
// ============================================================

export function createEdgeRegistry() {

    // --------------------------------------------------------
    // Здесь будут храниться все уникальные рёбра.
    //
    // Например:
    //
    // "0.123_0.456_0.789|0.234_0.567_0.890"
    //
    //        ↓
    //
    // массив точек границы
    // --------------------------------------------------------

    const edges = new Map();


    // ========================================================
    // ПОЛУЧИТЬ ГРАНИЦУ
    // ========================================================
    //
    // Если такое ребро уже существует —
    // возвращаем существующее.
    //
    // Если его ещё нет —
    // создаём через createWarpedEdge().
    //
    // ========================================================

    function getEdge(start, end) {

        const a =
            start.clone().normalize();


        const b =
            end.clone().normalize();


        // ----------------------------------------------------
        // Определяем канонический порядок.
        //
        // Поэтому:
        //
        // A → B
        //
        // и
        //
        // B → A
        //
        // получают одинаковый ключ.
        // ----------------------------------------------------

        let first = a;

        let second = b;

        let reversed = false;


        if (
            compareVectors(first, second) > 0
        ) {

            first = b;

            second = a;

            reversed = true;

        }


        // ----------------------------------------------------
        // Создаём уникальный ключ.
        // ----------------------------------------------------

        const key =
            createEdgeKey(
                first,
                second
            );


        // ====================================================
        // РЕБРО УЖЕ ЕСТЬ
        // ====================================================

        if (edges.has(key)) {

            const stored =
                edges.get(key);


            // Если запрашиваем ребро в обратном направлении,
            // возвращаем копию в обратном порядке.

            if (reversed) {

                return stored
                    .map(
                        point => point.clone()
                    )
                    .reverse();

            }


            return stored
                .map(
                    point => point.clone()
                );

        }


        // ====================================================
        // СОЗДАЁМ НОВОЕ РЕБРО
        // ====================================================

        const points =
            createWarpedEdge(
                first,
                second
            );


        // ----------------------------------------------------
        // Сохраняем именно каноническое направление.
        // ----------------------------------------------------

        edges.set(
            key,
            points.map(
                point => point.clone()
            )
        );


        // ----------------------------------------------------
        // Возвращаем в нужном направлении.
        // ----------------------------------------------------

        if (reversed) {

            return points
                .map(
                    point => point.clone()
                )
                .reverse();

        }


        return points
            .map(
                point => point.clone()
            );

    }


    // ========================================================
    // ПРОВЕРКА КОЛИЧЕСТВА РЁБЕР
    // ========================================================
    //
    // Пока это вспомогательная функция.
    //
    // Позже она позволит нам проверить:
    //
    // сколько уникальных границ действительно создано.
    //
    // ========================================================

    function getEdgeCount() {

        return edges.size;

    }


    // ========================================================
    // ОЧИСТКА
    // ========================================================
    //
    // На будущее.
    //
    // Позволяет полностью пересоздать карту.
    //
    // ========================================================

    function clear() {

        edges.clear();

    }


    // ========================================================
    // ПУБЛИЧНЫЙ API
    // ========================================================

    return {

        getEdge,

        getEdgeCount,

        clear

    };

}


// ============================================================
// СРАВНЕНИЕ ДВУХ VECTOR3
// ============================================================
//
// Используется только для определения канонического
// направления ребра.
//
// ============================================================

function compareVectors(a, b) {

    if (a.x !== b.x) {

        return a.x - b.x;

    }


    if (a.y !== b.y) {

        return a.y - b.y;

    }


    return a.z - b.z;

}


// ============================================================
// СОЗДАНИЕ УНИКАЛЬНОГО КЛЮЧА РЕБРА
// ============================================================

function createEdgeKey(a, b) {

    return [

        round(a.x),
        round(a.y),
        round(a.z),

        "|",

        round(b.x),
        round(b.y),
        round(b.z)

    ].join("");

}


// ============================================================
// ОКРУГЛЕНИЕ
// ============================================================

function round(value) {

    return value.toFixed(
        PRECISION
    );

}