import * as THREE from "three";


// ============================================================
// НАСТРОЙКИ ГРАНИЦЫ
// ============================================================

// Количество точек, из которых будет состоять граница.
// Больше точек = более плавная линия.
const SEGMENTS = 24;


// Сила естественного отклонения границы.
//
// 0.02 — почти прямая
// 0.04 — заметно извилистая
// 0.06 — сильно извилистая
//
// Начинаем с умеренного значения.
const WARP_STRENGTH = 0.015;


// Радиус относительно поверхности планеты.
const RADIUS = 1.012;


// ============================================================
// СОЗДАНИЕ ОБЩЕЙ ИСКРИВЛЁННОЙ ГРАНИЦЫ
// ============================================================
//
// start и end — две вершины Voronoi.
//
// ВАЖНО:
//
// createWarpedEdge(A, B)
//
// и
//
// createWarpedEdge(B, A)
//
// дадут ОДИНАКОВУЮ геометрию.
//
// Это критически важно, потому что одно и то же ребро
// принадлежит двум соседним субсекторам.
// ============================================================

export function createWarpedEdge(start, end) {

    // --------------------------------------------------------
    // Нормализуем точки.
    // --------------------------------------------------------

    const a = start.clone().normalize();

    const b = end.clone().normalize();


    // --------------------------------------------------------
    // Создаём каноническое направление ребра.
    //
    // Благодаря этому порядок A → B или B → A
    // не влияет на форму границы.
    // --------------------------------------------------------

    let first = a;
    let second = b;


    if (compareVectors(first, second) > 0) {

        first = b;
        second = a;

    }


    // --------------------------------------------------------
    // Вычисляем направление нормали к плоскости
    // большой окружности.
    //
    // Именно в этом направлении будем слегка
    // отклонять границу.
    // --------------------------------------------------------

    const warpDirection =
        new THREE.Vector3()
            .crossVectors(first, second);


    // Если точки практически совпадают,
    // просто возвращаем обычную линию.
    if (warpDirection.lengthSq() < 0.00000001) {

        return [
            a.clone().multiplyScalar(RADIUS),
            b.clone().multiplyScalar(RADIUS)
        ];

    }


    warpDirection.normalize();


    // --------------------------------------------------------
    // Получаем уникальный идентификатор ребра.
    //
    // Он нужен для детерминированной деформации.
    // --------------------------------------------------------

    const edgeKey =
        createEdgeKey(first, second);


    // --------------------------------------------------------
    // Получаем два псевдослучайных числа.
    //
    // Они всегда будут одинаковыми для одного и того же
    // ребра.
    // --------------------------------------------------------

    const random1 =
        seededRandom(edgeKey + "_A");


    const random2 =
        seededRandom(edgeKey + "_B");


    // --------------------------------------------------------
    // Направление искривления.
    //
    // Каждая граница может выгибаться немного
    // в свою сторону.
    // --------------------------------------------------------

    const direction =
        random1 < 0.5
            ? -1
            : 1;


    // --------------------------------------------------------
    // Сила искривления.
    //
    // Не все границы будут одинаково кривыми.
    // --------------------------------------------------------

    const strength =
        WARP_STRENGTH *
        (
            0.65 +
            random2 * 0.35
        ) *
        direction;


    // --------------------------------------------------------
    // Угол между концами.
    // --------------------------------------------------------

    const dot =
        THREE.MathUtils.clamp(
            a.dot(b),
            -1,
            1
        );


    const angle =
        Math.acos(dot);


    // --------------------------------------------------------
    // Если точки почти совпадают.
    // --------------------------------------------------------

    if (angle < 0.000001) {

        return [
            a.clone().multiplyScalar(RADIUS)
        ];

    }


    const sinAngle =
        Math.sin(angle);


    const points = [];


    // ========================================================
    // СОЗДАЁМ ГРАНИЦУ
    // ========================================================

    for (
        let i = 0;
        i <= SEGMENTS;
        i++
    ) {

        const t =
            i / SEGMENTS;


        // ----------------------------------------------------
        // Сферическая интерполяция между A и B.
        // ----------------------------------------------------

        const weightA =
            Math.sin(
                (1 - t) * angle
            ) /
            sinAngle;


        const weightB =
            Math.sin(
                t * angle
            ) /
            sinAngle;


        const point =
            a.clone()
                .multiplyScalar(weightA)
                .add(
                    b.clone()
                        .multiplyScalar(weightB)
                )
                .normalize();


        // ----------------------------------------------------
        // Функция формы искривления.
        //
        // На концах:
        //
        // t = 0 → 0
        // t = 1 → 0
        //
        // Поэтому вершины Voronoi никогда не смещаются.
        // ----------------------------------------------------

        const mainCurve =
            Math.sin(
                Math.PI * t
            );


        // ----------------------------------------------------
        // Вторичная небольшая неровность.
        //
        // Она делает границу менее похожей на идеальную
        // математическую дугу.
        // ----------------------------------------------------

        const secondaryCurve =
            Math.sin(
                Math.PI * 2 * t
            )
            *
            0.10;


        // ----------------------------------------------------
        // Итоговое отклонение.
        // ----------------------------------------------------

        const offset =
            (
                mainCurve +
                secondaryCurve
            )
            *
            strength;


        // ----------------------------------------------------
        // Смещаем точку.
        // ----------------------------------------------------

        point.add(
            warpDirection
                .clone()
                .multiplyScalar(offset)
        );


        // ----------------------------------------------------
        // Возвращаем точку обратно на сферу.
        // ----------------------------------------------------

        point.normalize();


        // ----------------------------------------------------
        // Немного выносим границу над поверхностью планеты.
        // ----------------------------------------------------

        point.multiplyScalar(RADIUS);


        points.push(point);

    }


    return points;

}


// ============================================================
// СРАВНЕНИЕ VECTOR3
// ============================================================
//
// Нужно только для определения единого порядка концов.
//
// ============================================================

function compareVectors(a, b) {

    if (a.x !== b.x) {

        return a.x - b.x;

    }


    if (a.y !== b.y) {

        return a.y - b.y;

    }


    return a.z - b.z;

}


// ============================================================
// СОЗДАНИЕ УНИКАЛЬНОГО КЛЮЧА РЕБРА
// ============================================================

function createEdgeKey(a, b) {

    return [

        a.x.toFixed(6),
        a.y.toFixed(6),
        a.z.toFixed(6),

        "|",

        b.x.toFixed(6),
        b.y.toFixed(6),
        b.z.toFixed(6)

    ].join("");

}


// ============================================================
// ДЕТЕРМИНИРОВАННЫЙ RANDOM
// ============================================================
//
// Одинаковая строка → одинаковое число.
//
// Поэтому форма карты не меняется после перезапуска.
// ============================================================

function seededRandom(string) {

    let hash = 2166136261;


    for (
        let i = 0;
        i < string.length;
        i++
    ) {

        hash ^= string.charCodeAt(i);

        hash +=
            (
                hash << 1
            ) +
            (
                hash << 4
            ) +
            (
                hash << 7
            ) +
            (
                hash << 8
            ) +
            (
                hash << 24
            );

    }


    return (
        hash >>> 0
    ) / 4294967295;

}